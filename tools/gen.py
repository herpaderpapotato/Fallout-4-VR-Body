"""Generate what FRIK's / the framework's CMake generates (configure_file + embed-binary) into frik-flat/generated/:
Version.h (FRIK's), EmbeddedTextFont.cpp (framework text font), resources.rc (FRIK's embedded config files).
Run: python -I frik-flat/tools/gen.py   (idempotent; only rewrites a file whose content changed)
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "generated"
VERSION = (0, 80, 1)


def write(path: Path, text: str, binary=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    data = text.encode("utf-8")
    if path.exists() and path.read_bytes() == data:
        return
    path.write_bytes(data)
    print("wrote", path.relative_to(ROOT))


def main():
    tpl = (ROOT / "cmake" / "Version.h.in").read_text(encoding="utf-8")
    ver = (tpl.replace("@PROJECT_VERSION_MAJOR@", str(VERSION[0])).replace("@PROJECT_VERSION_MINOR@", str(VERSION[1]))
           .replace("@PROJECT_VERSION_PATCH@", str(VERSION[2])).replace("@PROJECT_VERSION@", ".".join(map(str, VERSION)))
           .replace("@PROJECT_NAME@", "FRIK"))
    write(GEN / "Version.h", ver)

    font = (ROOT / "external" / "F4VR-CommonFramework" / "src" / "render" / "fonts" / "Roboto-Medium.ttf").read_bytes()
    lines = []
    for i in range(0, len(font), 16):
        lines.append("".join(f"0x{b:02x}," for b in font[i:i + 16]))
    src = ("// Generated from Roboto-Medium.ttf by frik-flat/tools/gen.py (= fw cmake/embed-binary.cmake) - do not edit.\n"
           "#include <cstddef>\n#include <cstdint>\n\nnamespace f4cf::render::internal\n{\n"
           "    extern const std::uint8_t TEXT_FONT_TTF[];\n    extern const std::size_t TEXT_FONT_TTF_SIZE;\n\n"
           "    const std::uint8_t TEXT_FONT_TTF[] = {\n" + "\n".join(lines) + "\n    };\n"
           f"    const std::size_t TEXT_FONT_TTF_SIZE = {len(font)};\n}}\n")
    write(GEN / "EmbeddedTextFont.cpp", src)

    rc = (ROOT / "cmake" / "resources.rc.in").read_text(encoding="utf-8")
    rc = rc.replace("@ROOT_DIR@/data", (ROOT / "data").as_posix())
    write(GEN / "resources.rc", '#include "' + (ROOT / "src" / "resources.h").as_posix() + '"\n' + rc
          if "resources.h" not in rc else rc)


if __name__ == "__main__":
    main()


# ---- address table (C4): analysis/db/frik_flat_symbols.csv -> generated/FrikFlatAddresses.inl
MANUAL = {
    # VR rva: (flat rva, note) - set by hand, see analysis/frik-flat-port.md section 1
    0xF29AC8: (0xD78CFE, "DoShow1stPerson 3rd-person SetAppCulled arg: VR movzx edx,r14b / flat 41 0F B6 D7 movzx edx,r15b"),
    0xDA09A0: (0xC403B0, "BSTEventSource<PlayerUpdateEvent>::Notify, verified by fo4flatvr W1 (call site C351F3)"),
    0x1D0DEE0: (0x17B43C0, "BSModelDB::Demand (loadNif): Ghidra, same signature, inner Demand inlined on flat"),
    0x1C21070: (0x16C6E00, "BSFlattenedBoneTree::GetBoneNode(str): Ghidra, same body (+0x148 vs VR +0x188)"),
}
# OG address-library ids (CommonLibF4VR REL::ID) used by vrshim for members the flat lib lacks: id -> (flat rva, note)
MANUAL_IDS = {
    943772: (0xC97060, "Actor::RequestDetectionLevel (1.10.163 DAA580, func_matches high)"),
}
STATUS = {"mapped": "kMapped", "mapped-site": "kMappedSite", "mapped-low": "kMappedLow"}


def gen_addresses():
    import csv
    src = ROOT / "analysis" / "db" / "frik_flat_symbols.csv"
    seen = {}
    with open(src, encoding="utf-8") as f:
        for r in csv.DictReader(f):
            is_id = r["kind"] == "id"
            key = (int(r["og_id"]) if is_id else int(r["vr_rva"], 16)), is_id
            name = r["ident"] or f'{r["file"]}:{r["line"]}'
            flat = int(r["flat_rva"], 16) if r["flat_rva"] else 0
            st = STATUS.get(r["status"], "kUnresolved") if flat else "kUnresolved"
            if not is_id and key[0] in MANUAL:
                flat, st = MANUAL[key[0]][0], "kManual"
            if key not in seen or (seen[key][1] == "kUnresolved" and st != "kUnresolved"):
                seen[key] = (flat, st, name, is_id or r["vr_section"] not in (".data", ".rdata", ".bss"))
    for i, (flat, note) in MANUAL_IDS.items():
        seen[(i, True)] = (flat, "kManual", note.split(" (")[0], True)
    rows = [f'    {{ 0x{k[0]:X}, 0x{v[0]:X}, AddrStatus::{v[1]}, {"true" if k[1] else "false"}, "{v[2]}", {"true" if v[3] else "false"} }},'
            for k, v in sorted(seen.items())]
    text = ("// Generated by frik-flat/tools/gen.py from analysis/db/frik_flat_symbols.csv - do not edit.\n"
            "// { VR 1.2.72 rva or VR address-library id, flat 1.11.240 rva (0 = none), status, isId, name, isCode }\n"
            + "\n".join(rows) + "\n")
    write(GEN / "FrikFlatAddresses.inl", text)


gen_addresses()
